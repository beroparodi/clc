def fit_power_law(rows, post):
    """Weighted least-squares fit of ln Q = ln Q1 + p ln r on one side of perihelion.
    Returns (p, sigma_p), the error scaled by the reduced chi-square."""
    import numpy as np
    d = np.array([x for x in rows if (x[0] > 0) == post])
    x, y, w = np.log(d[:, 1]), np.log(d[:, 2]), (d[:, 2] / d[:, 3])**2
    A = np.vstack([x, np.ones_like(x)]).T
    N = A.T @ (w[:, None] * A); c = np.linalg.solve(N, A.T @ (w * y))
    chi2 = (w * (y - A @ c)**2).sum() / (len(x) - 2)
    return c[0], np.sqrt(np.linalg.inv(N)[0, 0] * chi2)

def _rounded(rows, post):
    p, e = fit_power_law(rows, post)
    return round(float(p), 1), round(float(e), 1)

